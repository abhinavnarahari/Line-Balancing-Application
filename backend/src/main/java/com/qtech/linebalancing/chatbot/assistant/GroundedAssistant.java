package com.qtech.linebalancing.chatbot.assistant;

import com.qtech.linebalancing.chatbot.assistant.nlu.*;
import com.qtech.linebalancing.chatbot.assistant.skills.HelpSkill;
import com.qtech.linebalancing.chatbot.assistant.skills.Skill;
import com.qtech.linebalancing.chatbot.dto.ChatContextDto;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

import java.time.LocalTime;
import java.time.format.DateTimeFormatter;
import java.util.*;
import java.util.stream.Collectors;

/**
 * SewNexa AI orchestrator. Pipeline:
 * <ol>
 *   <li>Understand: rule-based {@link QuestionAnalyzer} (entities resolved only against application records);
 *       optional {@link LlmIntentRouter} only when the rules cannot route the question.</li>
 *   <li>Complete: follow-ups reuse the previous intent/records; the open page supplies a line/order/style.</li>
 *   <li>Check: ask which record is meant when it is missing or ambiguous; report names that don't exist.</li>
 *   <li>Answer: the matching {@link Skill} computes the reply from the database in a read-only transaction.</li>
 * </ol>
 * Every figure in an answer is produced by code from application data; nothing is generated by a language model.
 */
@Slf4j
@Service
public class GroundedAssistant {

    /** Intents whose skill cannot run without their primary record. */
    private static final Set<Intent> NEEDS_PRIMARY = EnumSet.of(Intent.OPERATOR_PROFILE, Intent.TOP_OPERATORS_FOR_OPERATION,
            Intent.OPERATION_DETAILS, Intent.STYLE_DETAILS, Intent.LINE_DETAILS, Intent.ORDER_STATUS);

    private static final DateTimeFormatter TIME = DateTimeFormatter.ofPattern("HH:mm");

    private final QuestionAnalyzer analyzer;
    private final EntityCatalog catalog;
    private final LlmIntentRouter llmRouter;
    private final HelpSkill helpSkill;
    private final Map<Intent, Skill> skills = new EnumMap<>(Intent.class);
    private final TransactionTemplate readOnlyTx;

    public GroundedAssistant(QuestionAnalyzer analyzer, EntityCatalog catalog, LlmIntentRouter llmRouter, HelpSkill helpSkill,
                             List<Skill> allSkills, PlatformTransactionManager transactionManager) {
        this.analyzer = analyzer;
        this.catalog = catalog;
        this.llmRouter = llmRouter;
        this.helpSkill = helpSkill;
        allSkills.forEach(s -> s.intents().forEach(i -> {
            if (skills.put(i, s) != null) throw new IllegalStateException("Two skills handle " + i);
        }));
        for (Intent i : Intent.values()) {
            if (!skills.containsKey(i)) throw new IllegalStateException("No skill handles " + i);
        }
        this.readOnlyTx = new TransactionTemplate(transactionManager);
        this.readOnlyTx.setReadOnly(true);
    }

    /** Result of one turn, including what to remember for follow-ups. */
    public record Reply(Answer answer, Intent intent, String routedBy, ConversationState state) {
    }

    public Reply ask(String message, ChatContextDto context, ConversationState previous) {
        long started = System.currentTimeMillis();
        AnalyzedQuestion q = analyzer.analyze(message);
        String routedBy = "RULES";

        // Follow-ups: "and LINE-02?", "what about yesterday?", "what is its SMV?"
        // Override the detected intent only when the question was not understood on its own, or when it is an
        // "and X?" continuation that names a new record without saying what to do with it.
        boolean notUnderstood = q.intent() == Intent.UNKNOWN || q.intent() == Intent.OUT_OF_SCOPE;
        boolean entityOnlyContinuation = analyzer.startsLikeFollowUp(q) && q.confidence() <= 0.4 && !q.entities().isEmpty();
        if (previous != null && ((notUnderstood && analyzer.looksLikeFollowUp(q)) || entityOnlyContinuation)) {
            q = q.withIntent(previous.intent(), true);
            routedBy = "FOLLOW_UP";
        }
        if (q.intent() == Intent.UNKNOWN && llmRouter.isEnabled()) {
            Optional<AnalyzedQuestion> routed = llmRouter.route(q);
            if (routed.isPresent()) {
                q = routed.get();
                routedBy = "LLM_ROUTER";
            }
        }
        q = complete(q, previous, context);

        Answer answer;
        Intent primaryMissingFor = missingPrimary(q);
        if (primaryMissingFor != null) {
            answer = askForPrimary(q);
        } else {
            AnalyzedQuestion finalQ = q;
            try {
                answer = readOnlyTx.execute(status -> skills.get(finalQ.intent()).answer(finalQ));
            } catch (RuntimeException e) {
                log.error("SewNexa AI failed answering intent {} for '{}'", finalQ.intent(), message, e);
                answer = Answer.notAvailable("I couldn't read the data needed to answer that just now. Please try again in a moment.", List.of());
            }
        }

        Map<EntityType, String> resolved = new EnumMap<>(EntityType.class);
        q.entities().forEach((type, refs) -> { if (!refs.isEmpty()) resolved.put(type, refs.get(0).key()); });
        Intent remembered = isAnswerIntent(q.intent()) ? q.intent() : (previous != null ? previous.intent() : null);
        ConversationState state = remembered == null ? previous : new ConversationState(remembered, resolved.isEmpty() && previous != null ? previous.entities() : resolved);

        log.info("SewNexa AI intent={} routedBy={} entities={} dataAvailable={} in {} ms", q.intent(), routedBy,
                resolved, answer.dataAvailable(), System.currentTimeMillis() - started);
        return new Reply(withSources(answer), q.intent(), routedBy, state);
    }

    /** Fill the primary record from the previous turn (follow-ups / pronouns) or from the page the user is on. */
    private AnalyzedQuestion complete(AnalyzedQuestion q, ConversationState previous, ChatContextDto context) {
        if (previous != null && (q.followUp() || analyzer.looksLikeFollowUp(q))) {
            for (Map.Entry<EntityType, String> e : previous.entities().entrySet()) {
                if (!q.has(e.getKey())) {
                    Optional<EntityRef> ref = catalog.find(e.getKey(), e.getValue());
                    if (ref.isPresent()) q = q.withEntity(ref.get());
                }
            }
        }
        EntityType primary = q.intent().primaryEntity();
        if (primary != null && !q.has(primary) && q.ambiguous().isEmpty() && q.unresolved() == null && context != null) {
            String key = switch (primary) {
                case LINE -> context.getLineId() != null ? String.valueOf(context.getLineId()) : null;
                case ORDER -> context.getOrderId() != null ? String.valueOf(context.getOrderId()) : null;
                case STYLE -> context.getStyleId() != null ? String.valueOf(context.getStyleId()) : null;
                default -> null;
            };
            Optional<EntityRef> ref = catalog.find(primary, key);
            if (ref.isPresent()) q = q.withEntity(ref.get());
        }
        return q;
    }

    private static Intent missingPrimary(AnalyzedQuestion q) {
        return NEEDS_PRIMARY.contains(q.intent()) && !q.has(q.intent().primaryEntity()) ? q.intent() : null;
    }

    private Answer askForPrimary(AnalyzedQuestion q) {
        if (!q.ambiguous().isEmpty() || q.unresolved() != null) {
            return helpSkill.answer(q.withIntent(Intent.UNKNOWN, q.followUp()));
        }
        EntityType type = q.intent().primaryEntity();
        List<EntityRef> options = catalog.all(type);
        if (options.isEmpty()) return Answer.notAvailable("There are no " + type.label() + "s in SewNexa yet.", List.of());
        String list = options.stream().limit(8).map(EntityRef::display).collect(Collectors.joining(", "));
        return Answer.notAvailable("Which " + type.label() + " do you mean? For example: " + list + (options.size() > 8 ? ", …" : "") + ".",
                options.stream().limit(3).map(r -> rephrase(q.intent(), r)).toList());
    }

    private static String rephrase(Intent intent, EntityRef r) {
        String name = r.display().replaceAll(" \\(.*\\)$", "");
        return switch (intent) {
            case TOP_OPERATORS_FOR_OPERATION -> "Who are the best operators for " + name + "?";
            case OPERATION_DETAILS -> "What is the SMV of " + name + "?";
            case ORDER_STATUS -> "What is the progress of order " + name + "?";
            case LINE_DETAILS -> "Show details of " + r.display().split(" — ")[0];
            case STYLE_DETAILS -> "Show style " + name;
            default -> "Show " + r.type().label() + " " + name;
        };
    }

    private static boolean isAnswerIntent(Intent i) {
        return i != Intent.UNKNOWN && i != Intent.OUT_OF_SCOPE && i != Intent.GREETING && i != Intent.HOW_TO;
    }

    /** Appends where the figures came from and when, so users can trust and verify the answer. */
    private static Answer withSources(Answer a) {
        if (!a.dataAvailable() || a.sources().isEmpty()) return a;
        String footer = "\n\n*Source: " + String.join(", ", a.sources()) + " · as of " + LocalTime.now().format(TIME) + "*";
        return new Answer(a.text() + footer, a.payload(), a.sources(), a.suggestions(), true, a.resolvedEntities());
    }
}
